    static let phaseCount = 8
    static let framesPerSecond: Double = 12    // per the sheet manifest
    static let widthFraction: CGFloat = 0.034
    /// Waddling pace as a fraction of the view's width per second, so it
    /// moves at the same speed however long that day's circuit is.
    static let speedFraction: CGFloat = 0.0026

    private static var cache: (day: Int, course: CampaignRoute.Course)?

    static func course(forDay day: Int) -> CampaignRoute.Course {
        if let c = cache, c.day == day { return c.course }
        let course = CampaignRoute.closedCourse(
            seed: day &* 7919 &+ 101,        // its own stream, not the pirate's
            centreX: 1100...1400,
            centreY: 1200...1400,
            radius: 60...150,
            aspect: 1.1,
            attempts: 200,
            minimumLength: 380
        ) { mask.allows($0, imageSize: CampaignMapAsset.imageSize) }
        cache = (day, course)
        return course
    }

    /// The sheet measures clockwise screen degrees with east at 0.
    static func frameIndex(dx: CGFloat, dy: CGFloat, elapsed: Double) -> Int {
        var deg = atan2(dy, dx) * 180 / .pi
        if deg < 0 { deg += 360 }
        let dir = Int((deg / 360 * CGFloat(directionCount)).rounded()) % directionCount
        let phase = Int(elapsed * framesPerSecond) % phaseCount
        return dir * phaseCount + phase
    }
}

struct CampaignBeaver: View {
    var viewSize: CGSize

    var body: some View {
        let day = CampaignPirateVoyage.dayNumber()
        let course = CampaignBeaverRoute.course(forDay: day)
        let width = viewSize.width * CampaignBeaverRoute.widthFraction
        let sprite = UIImage(named: "beaver_walk_0")
        let height = width * (sprite?.size.height ?? 1) / (sprite?.size.width ?? 1)
        let lengthPoints = (course.lengths.last ?? 1)
            * viewSize.width / CampaignMapAsset.safeRect.width
        let seconds = Double(lengthPoints / max(viewSize.width * CampaignBeaverRoute.speedFraction, 0.01))

        return Group {
            if sprite != nil {
                TimelineView(.animation(minimumInterval: 1.0 / 30.0)) { timeline in
                    let elapsed = timeline.date.timeIntervalSinceReferenceDate
                    let progress = elapsed / seconds
                    let s = CampaignRoute.sample(progress, on: course)
                    let centre = CampaignMapLayout.viewPoint(
                        forImagePoint: s.point,
                        imageSize: CampaignMapAsset.imageSize,
                        safeRect: CampaignMapAsset.safeRect,
                        viewSize: viewSize
                    )
                    Image("beaver_walk_\(CampaignBeaverRoute.frameIndex(dx: s.dx, dy: s.dy, elapsed: elapsed))")
                        .resizable()
                        .interpolation(.high)
                        .scaledToFit()
                        .frame(width: width, height: height)
                        .shadow(color: .black.opacity(0.28), radius: width * 0.06, y: height * 0.06)
                        .position(centre)
                }
                .allowsHitTesting(false)
            }
        }
    }
}
